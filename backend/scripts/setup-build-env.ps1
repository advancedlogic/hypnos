<#
.SYNOPSIS
  Detects the toolchain pieces the native Hypnos build needs on Windows and writes them to the
  git-ignored <repo>\.cargo\config.toml (machine-specific), leaving backend\.cargo\config.toml portable.

  Detected / written:
    - CUDAARCHS / CUDA_COMPUTE_CAP  : from nvidia-smi (compute capability of GPU 0), else "native"
    - CMAKE_CUDA_ARCHITECTURES      : the same GPU as device code (forwarded to both ggml builds;
                                      without it ggml compiles its 9-target portable list)
    - CUDAHOSTCXX / CMAKE_CUDA_HOST_COMPILER : an MSVC 14.4x cl.exe (CUDA 13.0 does not support 14.5x)
    - [build] rustc / rustdoc       : the rustup "stable" toolchain, when another rustc shadows it on PATH

.EXAMPLE
  powershell -ExecutionPolicy Bypass -File backend\scripts\setup-build-env.ps1
#>
$ErrorActionPreference = "Stop"
$repo = Resolve-Path (Join-Path $PSScriptRoot "..\..")
$outDir = Join-Path $repo ".cargo"
$outFile = Join-Path $outDir "config.toml"
New-Item -ItemType Directory -Force $outDir | Out-Null

$env_lines = @()
$build_lines = @()
$notes = @()

# --- GPU architecture ---------------------------------------------------------------------------
$arch = "native"
try {
    $cap = (& nvidia-smi --query-gpu=compute_cap --format=csv,noheader 2>$null | Select-Object -First 1).Trim()
    if ($cap -match '^(\d+)\.(\d+)$') { $arch = "$($Matches[1])$($Matches[2])"; $notes += "GPU compute capability $cap -> CUDAARCHS=$arch" }
} catch { $notes += "nvidia-smi not found; CUDAARCHS=native (CMake probes the GPU at configure time)" }
$env_lines += "CUDAARCHS = `"$arch`""
$env_lines += "CUDA_COMPUTE_CAP = `"$arch`""
# Blackwell and newer: the "a" variant, as ggml's own list uses (FP4 tensor cores).
$cmakeArch = "native"
if ($arch -ne "native") { $cmakeArch = if ([int]$arch -ge 100) { "${arch}a-real" } else { "${arch}-real" } }
$env_lines += "CMAKE_CUDA_ARCHITECTURES = `"$cmakeArch`""

# --- CUDA host compiler --------------------------------------------------------------------------
$cudaMajor = $null
if ($env:CUDA_PATH -and (Test-Path "$env:CUDA_PATH\bin\nvcc.exe")) {
    $v = (& "$env:CUDA_PATH\bin\nvcc.exe" --version | Select-String -Pattern 'release (\d+)\.(\d+)').Matches
    if ($v.Count -gt 0) { $cudaMajor = [int]$v[0].Groups[1].Value; $notes += "CUDA toolkit $($v[0].Groups[1].Value).$($v[0].Groups[2].Value) at $env:CUDA_PATH" }
} else {
    $notes += "CUDA_PATH not set or nvcc missing; GPU builds will not work (CPU-only: cargo build --no-default-features -p hypnos-backends)"
}

$vswhere = "${env:ProgramFiles(x86)}\Microsoft Visual Studio\Installer\vswhere.exe"
$hostCl = $null
if (Test-Path $vswhere) {
    $installs = & $vswhere -products * -requires Microsoft.VisualStudio.Component.VC.Tools.x86.x64 -property installationPath 2>$null
    $candidates = @()
    foreach ($inst in $installs) {
        Get-ChildItem -Directory "$inst\VC\Tools\MSVC" -ErrorAction SilentlyContinue | ForEach-Object {
            $cl = Join-Path $_.FullName "bin\HostX64\x64\cl.exe"
            if (Test-Path $cl) { $candidates += [pscustomobject]@{ Version = [version]$_.Name; Path = $cl } }
        }
    }
    # CUDA 12.x/13.0 support MSVC up to 14.4x. Prefer the newest 14.4x; fall back to the newest available.
    $supported = $candidates | Where-Object { $_.Version.Major -eq 14 -and $_.Version.Minor -le 44 } | Sort-Object Version -Descending
    $chosen = if ($supported) { $supported[0] } else { $candidates | Sort-Object Version -Descending | Select-Object -First 1 }
    if ($chosen) {
        $hostCl = $chosen.Path -replace '\\', '/'
        $notes += "CUDA host compiler: MSVC $($chosen.Version) ($hostCl)"
        if (-not $supported) { $notes += "WARNING: no MSVC 14.4x toolset found; nvcc may crash with the newer toolset. Install 'MSVC v143 - VS 2022 C++ x64/x86 build tools (v14.44)' via the Visual Studio Installer." }
    }
}
if ($hostCl) {
    $env_lines += "CUDAHOSTCXX = `"$hostCl`""
    $env_lines += "CMAKE_CUDA_HOST_COMPILER = `"$hostCl`""
}

# --- rustc pin ----------------------------------------------------------------------------------
$rustupRustc = Join-Path $env:USERPROFILE ".rustup\toolchains\stable-x86_64-pc-windows-msvc\bin\rustc.exe"
$pathRustc = (Get-Command rustc -ErrorAction SilentlyContinue).Source
if ((Test-Path $rustupRustc) -and $pathRustc -and ($pathRustc -notlike "*\.cargo\bin\*") -and ($pathRustc -notlike "*\.rustup\*")) {
    $tc = (Split-Path $rustupRustc) -replace '\\', '/'
    $build_lines += "rustc = `"$tc/rustc.exe`""
    $build_lines += "rustdoc = `"$tc/rustdoc.exe`""
    $notes += "rustc on PATH is $pathRustc (not rustup); pinning cargo to the rustup stable toolchain"
}

$content = @("# Generated by backend/scripts/setup-build-env.ps1 on $(Get-Date -Format s) for $env:COMPUTERNAME.",
             "# Machine-specific; git-ignored. Re-run the script after changing GPU, CUDA or Visual Studio.", "")
if ($build_lines.Count -gt 0) { $content += "[build]"; $content += $build_lines; $content += "" }
$content += "[env]"; $content += $env_lines
Set-Content -Path $outFile -Value ($content -join "`n") -Encoding utf8

Write-Host "Wrote $outFile"
$notes | ForEach-Object { Write-Host "  - $_" }
Write-Host "Next: cd backend; cargo build   (or run.bat start backend)"
