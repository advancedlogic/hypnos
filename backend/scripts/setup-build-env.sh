#!/usr/bin/env bash
# Detects the toolchain pieces the native Hypnos build needs on Linux/macOS and writes them to the
# git-ignored <repo>/.cargo/config.toml (machine-specific), leaving backend/.cargo/config.toml portable.
#
#   CUDAARCHS / CUDA_COMPUTE_CAP : from nvidia-smi (compute capability of GPU 0), else "native"
#   CUDAHOSTCXX                  : a g++ version supported by the installed CUDA (13.x: g++ <= 14, 12.x: g++ <= 13)
#   macOS (Apple Silicon)        : no CUDA; only MACOSX_DEPLOYMENT_TARGET, the engines use Metal
#
# Usage: ./backend/scripts/setup-build-env.sh
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
OUT_DIR="$ROOT/.cargo"
OUT="$OUT_DIR/config.toml"
mkdir -p "$OUT_DIR"
notes=()
env_lines=()

if [ "$(uname -s)" = Darwin ]; then
    [ "$(uname -m)" = arm64 ] || echo "WARNING: Intel Macs are not supported (Metal + unified memory needs Apple Silicon)"
    {
        echo "# Generated by backend/scripts/setup-build-env.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ) for $(hostname)."
        echo "# Machine-specific; git-ignored. macOS: the engines use Metal, no CUDA settings needed."
        echo
        echo "[env]"
        echo "MACOSX_DEPLOYMENT_TARGET = \"14.0\""
    } > "$OUT"
    echo "Wrote $OUT"
    for tool in cmake ninja; do
        command -v "$tool" >/dev/null 2>&1 || echo "  - MISSING: $tool (brew install cmake ninja)"
    done
    xcrun -f metal >/dev/null 2>&1 || echo "  - MISSING: Metal compiler (xcode-select --install)"
    echo "Next: ./run.sh build backend"
    echo "  (= cd backend && cargo build --release -p hypnos-server --no-default-features --features metal)"
    exit 0
fi

# --- GPU architecture ----------------------------------------------------------------------------
arch="native"
if command -v nvidia-smi >/dev/null 2>&1; then
    cap="$(nvidia-smi --query-gpu=compute_cap --format=csv,noheader 2>/dev/null | head -n1 | tr -d ' ')"
    if [[ "$cap" =~ ^([0-9]+)\.([0-9]+)$ ]]; then
        arch="${BASH_REMATCH[1]}${BASH_REMATCH[2]}"
        notes+=("GPU compute capability $cap -> CUDAARCHS=$arch")
    fi
else
    notes+=("nvidia-smi not found; CUDAARCHS=native (CMake probes the GPU at configure time)")
fi
env_lines+=("CUDAARCHS = \"$arch\"" "CUDA_COMPUTE_CAP = \"$arch\"")

# --- CUDA host compiler --------------------------------------------------------------------------
NVCC="${CUDA_PATH:-/usr/local/cuda}/bin/nvcc"
if [ -x "$NVCC" ]; then
    cuda_major="$("$NVCC" --version | sed -n 's/.*release \([0-9]*\)\.\([0-9]*\).*/\1/p' | head -n1)"
    notes+=("CUDA toolkit major version $cuda_major at $(dirname "$(dirname "$NVCC")")")
    max_gcc=14
    [ "${cuda_major:-13}" -le 12 ] && max_gcc=13
    host=""
    for v in $(seq "$max_gcc" -1 9); do
        if command -v "g++-$v" >/dev/null 2>&1; then host="$(command -v "g++-$v")"; break; fi
    done
    if [ -z "$host" ] && command -v g++ >/dev/null 2>&1; then
        gv="$(g++ -dumpversion | cut -d. -f1)"
        if [ "$gv" -le "$max_gcc" ]; then host="$(command -v g++)"; else notes+=("WARNING: g++ $gv is newer than CUDA $cuda_major supports (<= $max_gcc); install g++-$max_gcc"); fi
    fi
    if [ -n "$host" ]; then
        env_lines+=("CUDAHOSTCXX = \"$host\"")
        notes+=("CUDA host compiler: $host")
    fi
else
    notes+=("nvcc not found (CUDA_PATH or /usr/local/cuda); GPU builds will not work (CPU-only: cargo build --no-default-features -p hypnos-backends)")
fi

{
    echo "# Generated by backend/scripts/setup-build-env.sh on $(date -Is) for $(hostname)."
    echo "# Machine-specific; git-ignored. Re-run after changing GPU, CUDA or compilers."
    echo
    echo "[env]"
    printf '%s\n' "${env_lines[@]}"
} > "$OUT"

echo "Wrote $OUT"
for n in "${notes[@]}"; do echo "  - $n"; done
echo "Next: cd backend && cargo build   (or ./run.sh start backend)"
