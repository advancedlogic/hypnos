//! Bounded in-memory log of API calls, served on `GET /v1/logs` and shown by the playground's
//! "Request Logs" tab. Every inference request leaves one [`RequestRecord`]: the middleware
//! creates it from the route, status and duration plus the [`LogDetails`] the handler attached
//! to its response (model, token counts, telemetry; at `debug` the prompt and completion text;
//! at `trace` the request and response payloads with media replaced by placeholders). Streaming
//! handlers finish their record later through [`RequestLog::update`].

use std::collections::VecDeque;
use std::sync::atomic::{AtomicU8, Ordering};

use hypnos_core::openai::{ExecutionTelemetry, TokenUsage};
use parking_lot::Mutex;
use serde::{Deserialize, Serialize};
use serde_json::Value;

/// Strings longer than this are shortened in captured payloads.
const MAX_PAYLOAD_STRING: usize = 4096;
/// Strings longer than this with no whitespace are treated as encoded media.
const MEDIA_STRING_MIN: usize = 1024;
/// Prompt / completion text captured at `debug` is cut here.
pub const MAX_TEXT: usize = 16 * 1024;

/// How much of each call is kept, least to most verbose.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Serialize, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum LogLevel {
    Off = 0,
    /// Failed calls only (5xx).
    Error = 1,
    /// Rejected and failed calls (4xx and 5xx).
    Warn = 2,
    /// Metadata of every call.
    Info = 3,
    /// Plus prompt and completion text.
    Debug = 4,
    /// Plus request and response payloads.
    Trace = 5,
}

impl LogLevel {
    pub fn parse(s: &str) -> Option<Self> {
        match s.trim().to_ascii_lowercase().as_str() {
            "off" => Some(Self::Off),
            "error" => Some(Self::Error),
            "warn" | "warning" => Some(Self::Warn),
            "info" => Some(Self::Info),
            "debug" => Some(Self::Debug),
            "trace" => Some(Self::Trace),
            _ => None,
        }
    }

    pub fn as_str(self) -> &'static str {
        match self {
            Self::Off => "off",
            Self::Error => "error",
            Self::Warn => "warn",
            Self::Info => "info",
            Self::Debug => "debug",
            Self::Trace => "trace",
        }
    }

    fn from_u8(v: u8) -> Self {
        match v {
            0 => Self::Off,
            1 => Self::Error,
            2 => Self::Warn,
            3 => Self::Info,
            4 => Self::Debug,
            _ => Self::Trace,
        }
    }
}

/// Request id generated by the middleware, available to handlers as an extension.
#[derive(Debug, Clone)]
pub struct RequestId(pub String);

/// What a handler knows about its call. Attached to the response as an extension; the
/// middleware merges it into the record.
#[derive(Debug, Clone, Default)]
pub struct LogDetails {
    pub model: Option<String>,
    pub stream: bool,
    pub usage: Option<TokenUsage>,
    pub telemetry: Option<ExecutionTelemetry>,
    pub input: Option<String>,
    pub output: Option<String>,
    pub request_payload: Option<Value>,
    pub response_payload: Option<Value>,
    pub error: Option<String>,
}

impl LogDetails {
    pub fn with_error(mut self, error: impl ToString) -> Self {
        self.error = Some(error.to_string());
        self
    }
}

#[derive(Debug, Clone, Serialize)]
pub struct RequestRecord {
    pub id: String,
    pub route: String,
    pub method: String,
    pub status: u16,
    /// RFC 3339 timestamp of the request's arrival.
    pub started_at: String,
    pub duration_ms: f64,
    pub model: Option<String>,
    pub stream: bool,
    pub tokens_in: Option<u32>,
    pub tokens_out: Option<u32>,
    pub cached_tokens: Option<u32>,
    /// Decode tokens per second (chat) or prefill tokens per second (embeddings).
    pub tokens_per_s: Option<f64>,
    pub inference_ms: Option<f64>,
    pub tier_switch_ms: Option<f64>,
    pub previous_tier: Option<String>,
    pub error: Option<String>,
    /// Level the record was captured at (decides which optional fields are present).
    pub level: LogLevel,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub input: Option<String>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub output: Option<String>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub request_payload: Option<Value>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub response_payload: Option<Value>,
    /// Some captured text or payload was shortened.
    pub truncated: bool,
}

impl RequestRecord {
    /// A record with only what the middleware knows; the handler's details fill the rest.
    pub fn new(
        id: String,
        route: String,
        method: String,
        status: u16,
        started_at: String,
        duration_ms: f64,
    ) -> Self {
        Self {
            id,
            route,
            method,
            status,
            started_at,
            duration_ms,
            model: None,
            stream: false,
            tokens_in: None,
            tokens_out: None,
            cached_tokens: None,
            tokens_per_s: None,
            inference_ms: None,
            tier_switch_ms: None,
            previous_tier: None,
            error: None,
            level: LogLevel::Info,
            input: None,
            output: None,
            request_payload: None,
            response_payload: None,
            truncated: false,
        }
    }

    /// Copies the usage and telemetry numbers into the record's columns.
    pub fn apply_details(&mut self, d: LogDetails, level: LogLevel) {
        if d.model.is_some() {
            self.model = d.model;
        }
        self.stream |= d.stream;
        if let Some(u) = &d.usage {
            self.tokens_in = Some(u.prompt_tokens);
            self.tokens_out = Some(u.completion_tokens);
            self.cached_tokens = u.prompt_tokens_details.as_ref().map(|p| p.cached_tokens);
        }
        if let Some(t) = &d.telemetry {
            self.inference_ms = Some(t.inference_latency_ms);
            self.tier_switch_ms = Some(t.tier_switch_latency_ms);
            self.previous_tier = Some(format!("{:?}", t.previous_tier));
            self.tokens_per_s = t
                .engine
                .decode_tokens_per_s
                .or(t.engine.prefill_tokens_per_s);
            if let Some(c) = t.engine.cached_tokens {
                self.cached_tokens.get_or_insert(c);
            }
        }
        if d.error.is_some() {
            self.error = d.error;
        }
        if level >= LogLevel::Debug {
            if let Some(s) = d.input {
                let (s, cut) = truncate_text(&s, MAX_TEXT);
                self.input = Some(s);
                self.truncated |= cut;
            }
            if let Some(s) = d.output {
                let (s, cut) = truncate_text(&s, MAX_TEXT);
                self.output = Some(s);
                self.truncated |= cut;
            }
        }
        if level >= LogLevel::Trace {
            if let Some(v) = d.request_payload {
                let (v, cut) = scrub_payload(v);
                self.request_payload = Some(v);
                self.truncated |= cut;
            }
            if let Some(v) = d.response_payload {
                let (v, cut) = scrub_payload(v);
                self.response_payload = Some(v);
                self.truncated |= cut;
            }
        }
    }

    /// The record without its bulky optional fields (list view).
    fn summary(&self) -> Self {
        Self {
            input: None,
            output: None,
            request_payload: None,
            response_payload: None,
            ..self.clone()
        }
    }
}

/// Filters for the list endpoint. Empty strings match everything.
#[derive(Debug, Clone, Default, Deserialize)]
pub struct LogFilter {
    #[serde(default)]
    pub model: Option<String>,
    #[serde(default)]
    pub route: Option<String>,
    /// `ok`, `error` (any 4xx/5xx), `4xx` or `5xx`.
    #[serde(default)]
    pub status: Option<String>,
    #[serde(default)]
    pub limit: Option<usize>,
}

impl LogFilter {
    fn matches(&self, r: &RequestRecord) -> bool {
        if let Some(m) = self.model.as_deref().filter(|s| !s.is_empty()) {
            if !r.model.as_deref().is_some_and(|rm| rm.contains(m)) {
                return false;
            }
        }
        if let Some(route) = self.route.as_deref().filter(|s| !s.is_empty()) {
            if !r.route.contains(route) {
                return false;
            }
        }
        match self.status.as_deref().map(str::trim) {
            Some("ok") => r.status < 400,
            Some("error") => r.status >= 400,
            Some("4xx") => (400..500).contains(&r.status),
            Some("5xx") => r.status >= 500,
            _ => true,
        }
    }
}

#[derive(Debug)]
pub struct RequestLog {
    capacity: usize,
    level: AtomicU8,
    records: Mutex<VecDeque<RequestRecord>>,
}

impl RequestLog {
    pub fn new(level: LogLevel, capacity: usize) -> Self {
        Self {
            capacity,
            level: AtomicU8::new(level as u8),
            records: Mutex::new(VecDeque::with_capacity(capacity.min(1024))),
        }
    }

    pub fn level(&self) -> LogLevel {
        LogLevel::from_u8(self.level.load(Ordering::Relaxed))
    }

    pub fn set_level(&self, level: LogLevel) {
        self.level.store(level as u8, Ordering::Relaxed);
    }

    pub fn capacity(&self) -> usize {
        self.capacity
    }

    pub fn capture_text(&self) -> bool {
        self.level() >= LogLevel::Debug
    }

    pub fn capture_payloads(&self) -> bool {
        self.level() >= LogLevel::Trace
    }

    /// Stores `record` if the current level keeps calls with its status. Newest first.
    pub fn record(&self, mut record: RequestRecord, details: Option<LogDetails>) {
        let level = self.level();
        let keep = match level {
            LogLevel::Off => false,
            LogLevel::Error => record.status >= 500,
            LogLevel::Warn => record.status >= 400,
            _ => true,
        };
        if !keep || self.capacity == 0 {
            return;
        }
        record.level = level;
        if let Some(d) = details {
            record.apply_details(d, level);
        }
        let mut records = self.records.lock();
        records.push_front(record);
        while records.len() > self.capacity {
            records.pop_back();
        }
    }

    /// Amends the record with `id` (streaming handlers learn usage after the headers went out).
    pub fn update(&self, id: &str, f: impl FnOnce(&mut RequestRecord, LogLevel)) {
        let level = self.level();
        let mut records = self.records.lock();
        if let Some(r) = records.iter_mut().find(|r| r.id == id) {
            f(r, level);
        }
    }

    /// Newest first, without text or payloads.
    pub fn list(&self, filter: &LogFilter) -> Vec<RequestRecord> {
        let limit = filter.limit.unwrap_or(100).clamp(1, 1000);
        self.records
            .lock()
            .iter()
            .filter(|r| filter.matches(r))
            .take(limit)
            .map(RequestRecord::summary)
            .collect()
    }

    pub fn len(&self) -> usize {
        self.records.lock().len()
    }

    pub fn is_empty(&self) -> bool {
        self.len() == 0
    }

    pub fn get(&self, id: &str) -> Option<RequestRecord> {
        self.records.lock().iter().find(|r| r.id == id).cloned()
    }

    pub fn clear(&self) {
        self.records.lock().clear();
    }
}

/// Cuts `s` to at most `max` bytes on a character boundary.
pub fn truncate_text(s: &str, max: usize) -> (String, bool) {
    if s.len() <= max {
        return (s.to_string(), false);
    }
    let mut end = max;
    while !s.is_char_boundary(end) {
        end -= 1;
    }
    (
        format!("{}… [truncated, {} bytes total]", &s[..end], s.len()),
        true,
    )
}

/// Replaces media (data URLs, base64 blobs) in a payload with size placeholders and shortens
/// other long strings. Returns the scrubbed value and whether anything was changed.
pub fn scrub_payload(v: Value) -> (Value, bool) {
    let mut changed = false;
    let out = scrub(v, &mut changed);
    (out, changed)
}

fn scrub(v: Value, changed: &mut bool) -> Value {
    match v {
        Value::String(s) => {
            let looks_like_media = s.starts_with("data:")
                || (s.len() >= MEDIA_STRING_MIN && !s.contains(char::is_whitespace));
            if looks_like_media {
                *changed = true;
                Value::String(format!("<media omitted, {} chars>", s.len()))
            } else if s.len() > MAX_PAYLOAD_STRING {
                *changed = true;
                Value::String(truncate_text(&s, MAX_PAYLOAD_STRING).0)
            } else {
                Value::String(s)
            }
        }
        Value::Array(items) => Value::Array(items.into_iter().map(|x| scrub(x, changed)).collect()),
        Value::Object(map) => Value::Object(
            map.into_iter()
                .map(|(k, x)| (k, scrub(x, changed)))
                .collect(),
        ),
        other => other,
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;

    fn rec(id: &str, status: u16, model: &str) -> RequestRecord {
        RequestRecord {
            id: id.into(),
            route: "/v1/chat/completions".into(),
            method: "POST".into(),
            status,
            started_at: "2026-10-29T00:00:00Z".into(),
            duration_ms: 1.0,
            model: Some(model.into()),
            stream: false,
            tokens_in: None,
            tokens_out: None,
            cached_tokens: None,
            tokens_per_s: None,
            inference_ms: None,
            tier_switch_ms: None,
            previous_tier: None,
            error: None,
            level: LogLevel::Info,
            input: None,
            output: None,
            request_payload: None,
            response_payload: None,
            truncated: false,
        }
    }

    #[test]
    fn ring_keeps_newest_within_capacity_and_filters() {
        let log = RequestLog::new(LogLevel::Info, 3);
        for i in 0..5 {
            let model = if i % 2 == 0 { "a" } else { "b" };
            log.record(rec(&format!("r{i}"), 200, model), None);
        }
        let all = log.list(&LogFilter::default());
        assert_eq!(
            all.iter().map(|r| r.id.as_str()).collect::<Vec<_>>(),
            vec!["r4", "r3", "r2"]
        );
        let only_b = log.list(&LogFilter {
            model: Some("b".into()),
            ..Default::default()
        });
        assert_eq!(only_b.len(), 1);
        assert_eq!(only_b[0].id, "r3");
        assert!(log.get("r4").is_some());
        assert!(log.get("r0").is_none());
        log.clear();
        assert!(log.is_empty());
    }

    #[test]
    fn levels_gate_what_is_kept() {
        let log = RequestLog::new(LogLevel::Error, 10);
        log.record(rec("ok", 200, "m"), None);
        log.record(rec("bad", 400, "m"), None);
        log.record(rec("boom", 500, "m"), None);
        assert_eq!(log.len(), 1);
        log.set_level(LogLevel::Warn);
        log.record(rec("bad2", 400, "m"), None);
        assert_eq!(log.len(), 2);
        log.set_level(LogLevel::Off);
        log.record(rec("boom2", 500, "m"), None);
        assert_eq!(log.len(), 2);
        assert_eq!(LogLevel::parse("DEBUG"), Some(LogLevel::Debug));
        assert_eq!(LogLevel::parse("nope"), None);
    }

    #[test]
    fn text_and_payloads_depend_on_level() {
        let details = || LogDetails {
            model: Some("m".into()),
            input: Some("hello".into()),
            output: Some("world".into()),
            request_payload: Some(json!({"image": "data:image/png;base64,AAAA", "n": 1})),
            ..Default::default()
        };
        let info = RequestLog::new(LogLevel::Info, 10);
        info.record(rec("i", 200, "m"), Some(details()));
        let r = info.get("i").unwrap();
        assert!(r.input.is_none() && r.request_payload.is_none());

        let debug = RequestLog::new(LogLevel::Debug, 10);
        debug.record(rec("d", 200, "m"), Some(details()));
        let r = debug.get("d").unwrap();
        assert_eq!(r.input.as_deref(), Some("hello"));
        assert!(r.request_payload.is_none());

        let trace = RequestLog::new(LogLevel::Trace, 10);
        trace.record(rec("t", 200, "m"), Some(details()));
        let r = trace.get("t").unwrap();
        let payload = r.request_payload.unwrap();
        assert_eq!(payload["n"], 1);
        assert!(payload["image"]
            .as_str()
            .unwrap()
            .starts_with("<media omitted"));
        assert!(r.truncated);
        // The list view never carries the bulky fields.
        assert!(trace.list(&LogFilter::default())[0]
            .request_payload
            .is_none());
    }

    #[test]
    fn long_strings_are_cut_on_char_boundaries() {
        let s = "é".repeat(3000);
        let (cut, changed) = truncate_text(&s, 4000);
        assert!(changed);
        assert!(cut.starts_with("éé"));
        let (same, changed) = truncate_text("short", 100);
        assert!(!changed);
        assert_eq!(same, "short");
    }
}
